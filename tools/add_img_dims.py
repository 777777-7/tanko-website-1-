# -*- coding: utf-8 -*-
"""Add width/height (the file's real pixel size) to <img> tags that lack them, so
browsers reserve the space and the layout doesn't shift (CLS). Visual result is
unchanged because site.css sets img { max-width:100%; height:auto }.
Skips docs/zh (generated by tools/build_lang.py). Dry run by default.
Usage: python tools/add_img_dims.py [--apply]"""
import os, re, io, sys, glob
from urllib.parse import unquote
from PIL import Image
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DOCS = os.path.join(ROOT, "docs")
APPLY = "--apply" in sys.argv
size_cache, missing, files_changed, tags_changed = {}, set(), 0, 0

def dims(src):
    path = os.path.join(DOCS, *unquote(src.split("?")[0]).lstrip("/").split("/"))
    if path not in size_cache:
        try:
            with Image.open(path) as im: size_cache[path] = im.size
        except Exception:
            size_cache[path] = None; missing.add(src)
    return size_cache[path]

def fix(tag):
    global tags_changed
    if re.search(r"\swidth=", tag) and re.search(r"\sheight=", tag): return tag
    m = re.search(r'\ssrc="(/[^"]+)"', tag)
    if not m or re.search(r"\s(width|height)=", tag): return tag
    d = dims(m.group(1))
    if not d: return tag
    tags_changed += 1
    return tag[:4] + f' width="{d[0]}" height="{d[1]}"' + tag[4:]

for p in glob.glob(os.path.join(DOCS, "**", "*.html"), recursive=True):
    if os.sep + "zh" + os.sep in p: continue
    s = io.open(p, encoding="utf-8").read()
    n = re.sub(r"<img\b[^>]*>", lambda m: fix(m.group(0)), s)
    if n != s:
        files_changed += 1
        if APPLY: io.open(p, "w", encoding="utf-8", newline="").write(n)
print(("APPLIED" if APPLY else "DRY RUN"), f"{tags_changed} tags in {files_changed} files; missing image files: {len(missing)}", sorted(missing)[:5])
