def extract_keys():
    import build_lang as B
    gl = B.load_glossary('zh')
    keys = []
    for c in CATS:
        for f in [os.path.join(ROOT, 'docs', c, 'index.html')] + \
                 sorted(glob.glob(os.path.join(ROOT, 'docs', c, '*', 'index.html'))):
            for s in B.all_strings(io.open(f, encoding='utf-8').read()):
                if s not in gl and s not in keys:
                    keys.append(s)
    return keys


if __name__ == '__main__':
    keys = extract_keys()
    if len(keys) != len(TRANSLATIONS):
        raise SystemExit('ORDER DRIFT: %d keys but %d translations - refusing to '
                         'pair them up blindly.' % (len(keys), len(TRANSLATIONS)))
    out = dict(zip(keys, TRANSLATIONS))
    p = os.path.join(HERE, 'overlay_zh.json')
    prev = {}
    if os.path.exists(p):
        prev = json.load(io.open(p, encoding='utf-8'))
    prev.update(out)
    json.dump(prev, io.open(p, 'w', encoding='utf-8'), ensure_ascii=False,
              indent=0, sort_keys=True)
    print('overlay_zh.json: %d entries (%d added this run)' % (len(prev), len(out)))
