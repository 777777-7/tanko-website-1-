def extract_keys():
    import build_lang as B
    gl = B.load_glossary('zh')
    h = io.open(os.path.join(ROOT, 'docs', 'index.html'), encoding='utf-8').read()
    keys = []
    for s in B.all_strings(h):
        if s not in gl and s not in keys:
            keys.append(s)
    return keys


if __name__ == '__main__':
    keys = extract_keys()
    if len(keys) != len(TRANSLATIONS):
        raise SystemExit('ORDER DRIFT: %d keys but %d translations.'
                         % (len(keys), len(TRANSLATIONS)))
    p = os.path.join(HERE, 'overlay_zh.json')
    prev = json.load(io.open(p, encoding='utf-8')) if os.path.exists(p) else {}
    prev.update(dict(zip(keys, TRANSLATIONS)))
    json.dump(prev, io.open(p, 'w', encoding='utf-8'), ensure_ascii=False,
              indent=0, sort_keys=True)
    print('overlay_zh.json: %d entries (%d from homepage)' % (len(prev), len(keys)))
